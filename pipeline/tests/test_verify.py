META = {"title": "Weekly Sync", "date": "2026-10-07", "time": "14:00-15:03 KST (1h 03m)", "platform_label": "Google Meet",
        "self_name": "Me", "calendar": None}
RAW = ("# Transcript\n\nMeeting: Weekly Sync\nASR: whisper-large-v3 (2026)\n\n[00:00:13] Me\nThe pilot price is USD 7,500 for three sites "
       "and 90 days.\n\n[00:02:10] Remote\nThe license is USD 2,500 per site per year, twelve months.\n")


def note_text(title="Weekly Sync"):
    return note.normalize_header(sample_note(title), META, title).rstrip() + "\n\n<!-- generated by Claude Code 2.1.278 | model: claude-opus-5 -->\n"


class StatusLineTests(unittest.TestCase):
    def test_the_line_goes_right_under_the_h1_and_apart_from_the_header(self):
        marked = verify.set_status_line(note_text(), "numbers not found in the transcript: 180")
        lines = marked.splitlines()
        self.assertEqual(lines[:3], ["# Weekly Sync", "", "Verification: not applied (numbers not found in the transcript: 180)"])
        self.assertEqual(lines[3], "")
        self.assertTrue(lines[4].startswith("Date: "))
        self.assertEqual(marked.count("Verification:"), 1)
        # everything from the first heading on is untouched
        self.assertEqual(verify.body_of(marked), verify.body_of(note_text()))

    def test_setting_replaces_and_removing_restores_the_original_text(self):
        original = note_text()
        once = verify.set_status_line(original, "first reason")
        twice = verify.set_status_line(once, "second reason")
        self.assertEqual(twice.count("Verification:"), 1)
        self.assertIn("(second reason)", twice)
        self.assertNotIn("first reason", twice)
        self.assertEqual(verify.set_status_line(twice, None), original)
        self.assertEqual(verify.set_status_line(original, None), original)                    # nothing to remove: unchanged

    def test_a_status_line_the_model_wrote_is_removed_too_and_bold_variants_match(self):
        text = note_text().replace("Date:", "**Verification:** all good\nDate:", 1)
        self.assertNotIn("all good", verify.set_status_line(text, None))

    def test_a_note_without_an_h1_still_gets_the_line_at_the_top(self):
        text = "## Executive Summary\n- x\n"
        self.assertTrue(verify.set_status_line(text, "why").startswith("Verification: not applied (why)\n"))

    def test_the_reason_is_one_line_bounded_and_cannot_end_the_html_comment(self):
        reason = "a very\nlong reason -- with dashes " + "x" * 400
        line, footer = verify.status_line(reason), verify.not_applied_footer(reason)
        for text in (line, footer):
            self.assertNotIn("\n", text)
            self.assertNotIn("--", text.replace("<!--", "").replace("-->", ""))
        self.assertLessEqual(len(line), len("Verification: not applied ()") + verify.REASON_LIMIT)
        self.assertTrue(footer.startswith("<!-- Verification: not applied (") and footer.endswith(") -->"))
        self.assertIn("unknown reason", verify.status_line(""))


