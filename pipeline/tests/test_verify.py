class SpokenKoreanNumeralTests(unittest.TestCase):
    """A note that writes 3 for a spoken `세` / `셋` is supported (it must not be reported as `numbers not found in the transcript: 3`).
    The native numerals before a counter (`세 가지`, `두 명`, `한 번`) never matched: the alternative sat inside a group that
    must not be followed by a Hangul syllable, and the counter IS one; a plain `셋` as the last word of the text did not match either."""

    def values(self, text):
        return verify.spoken_values(text)

    def test_native_numerals_before_a_counter(self):
        cases = {"세 가지를 말했어요": "3", "세 개": "3", "세개": "3", "두 명이 참석했습니다": "2", "한 번 더 해 볼게요": "1", "네 번 반복했어요": "4",
                 "석 달 뒤에": "3", "넉 장": "4", "세 번째": "3", "세 문장을 말했어요": "3", "두 사람": "2", "한 단어": "1", "세 군데": "3",
                 "열 명": "10", "스물두 살": "22", "스무 살": "20", "열두 명이": "12"}
        for text, expected in cases.items():
            with self.subTest(text):
                self.assertIn(expected, self.values(text))

    def test_a_plain_native_numeral_at_the_end_of_the_text(self):
        for text in ("하나 둘 셋", "하나 둘 셋\n", "하나, 둘, 셋.", "[00:00:55] Me\n하나 둘 셋\n"):
            with self.subTest(text):
                self.assertTrue({"1", "2", "3"} <= self.values(text), self.values(text))

    def test_words_that_only_start_like_a_numeral_are_not_numbers(self):
        for text in ("세상은 넓다", "한국에서 왔어요", "네, 알겠습니다", "두려워요", "세금 이야기", "네 알겠습니다", "한가해요", "세미나", "넷플릭스"):
            with self.subTest(text):
                self.assertEqual(self.values(text), set())

    def test_a_note_may_write_the_digit_for_the_spoken_numeral(self):
        raw = "# Transcript\n\n[00:00:41] Me\n오늘은 세 문장만 말해 볼게요. 하나 둘 셋\n"
        allowed = verify.allowed_numbers([raw])
        self.assertEqual(verify.unsupported_numbers("- the user said 3 short sentences and counted 1, 2, 3.", allowed), [])
        self.assertEqual(verify.unsupported_numbers("- the user said 4 short sentences.", allowed), ["4"])


class VerifyNoteTests(TempCase):
    """verify_note() with a fake `call`: no process is started."""

    def setUp(self):
        super().setUp()
        self.cfg = make_cfg(self.root)
        self.seen = {}

    def call_returning(self, text=None, ok=True, kind="", error=""):
        def call(cfg, prompt, validate, **kw):
            self.seen.update(prompt=prompt, kw=kw)
            if not ok:
                return note.CallResult(False, error_kind=kind, error=error)
            value, problems = validate(text)
            if problems:
                return note.CallResult(False, error_kind="invalid_output", error="; ".join(problems))
            return note.CallResult(True, value=value, model="claude-opus-5")
        return call

    def run_verify(self, draft, call):
        return verify.verify_note(draft, RAW, None, META, self.cfg, Vocab(terms=["Acme"]), call=call)

    def test_the_call_is_made_for_the_verify_stage(self):
        res = self.run_verify(note_text(), self.call_returning(note_text()))
        self.assertTrue(res.ok, res.error)
        self.assertEqual(self.seen["kw"]["stage"], "verify")
        self.assertIn("<draft_note>", self.seen["prompt"])
        self.assertEqual(res.text.count("<!-- Verification:"), 1)

    def test_an_earlier_status_line_and_comment_are_not_part_of_what_is_checked_or_returned(self):
        marked = verify.set_status_line(note_text(), "boom one").rstrip() + "\n" + verify.not_applied_footer("boom one") + "\n"
        res = self.run_verify(marked, self.call_returning(note_text()))
        self.assertTrue(res.ok, res.error)
        self.assertNotIn("boom one", self.seen["prompt"])
        self.assertNotIn("not applied", res.text)
        self.assertNotRegex(res.text, r"(?m)^Verification:")

    def test_a_model_written_status_line_never_reaches_the_final_note(self):
        reply = note_text().replace("Date:", "Verification: fully verified by me\nDate:", 1)
        res = self.run_verify(note_text(), self.call_returning(reply))
        self.assertTrue(res.ok, res.error)
        self.assertNotIn("fully verified by me", res.text)

    def test_failures_are_reported_not_raised(self):
        res = self.run_verify(note_text(), self.call_returning(ok=False, kind="budget", error="claude call cap reached"))
        self.assertEqual((res.ok, res.error_kind, res.error), (False, "budget", "claude call cap reached"))

    def test_a_reply_with_an_invented_number_or_a_note_that_grew_is_rejected(self):
        invented = note_text().replace("USD 2,500", "USD 3,500")
        res = self.run_verify(note_text(), self.call_returning(invented))
        self.assertEqual((res.ok, res.error_kind), (False, "rejected"))
        self.assertIn("numbers not found in the transcript: 3500", res.error)
        grown = note_text().replace("## Open Questions", "## Open Questions\n" + "- one more line of invented detail\n" * 80)
        res = self.run_verify(note_text(), self.call_returning(grown))
        self.assertEqual((res.ok, res.error_kind), (False, "rejected"))
        self.assertIn("the verified note grew", res.error)


