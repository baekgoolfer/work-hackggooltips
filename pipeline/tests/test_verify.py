class SessionFactsTests(TempCase):
    def setUp(self):
        super().setUp()
        old = os.environ.get("TZ")
        os.environ["TZ"] = "Asia/Seoul"                   # note_meta prints the zone abbreviation of this machine: pin it
        time.tzset()
        self.addCleanup(self._restore_tz, old)
        self.cfg = make_cfg(self.root)
        self.seen = {}

    @staticmethod
    def _restore_tz(old):
        if old is None:
            os.environ.pop("TZ", None)
        else:
            os.environ["TZ"] = old
        time.tzset()

    def meta(self, start, duration):
        return note.note_meta({"start_time": start, "platform": "zoom", "platform_label": "Zoom"}, None, duration, "whisper", self.cfg)

    def reply(self, meta, extra=""):
        text = "# Zoom\n\nDate: x\nTime: y\nPlatform: z\nParticipants: Me\n\n" + ZOOM_BODY.format(extra=extra)
        return note.normalize_header(text, meta, "Zoom")

    def verify(self, reply, meta):
        def call(cfg, prompt, validate, **kw):
            value, problems = validate(reply)
            return note.CallResult(True, value=value, model="claude-opus-5") if not problems else \
                note.CallResult(False, error_kind="invalid_output", error="; ".join(problems))
        return verify.verify_note(self.reply(meta), ZOOM_RAW, None, meta, self.cfg, Vocab(terms=["Acme"]), call=call)

    def test_the_session_of_a_short_solo_call_has_the_header_the_pipeline_wrote(self):
        meta = self.meta("2026-10-10T17:17:09+09:00", 321.0)
        self.assertEqual((meta["date"], meta["time"]), ("2026-10-10", "17:17-17:22 KST (5m)"))
        self.assertIn("Time: 17:17-17:22 KST (5m)", self.reply(meta))

    def test_the_header_line_itself_is_not_an_invented_number(self):
        """The exact header of a short solo call, checked as a whole note (header included): the transcript alone does not support
        17:17 / 17:22 / 5, the session metadata does."""
        meta = self.meta("2026-10-10T17:17:09+09:00", 321.0)
        whole = self.reply(meta)
        self.assertTrue({"17", "22", "5"} <= set(verify.unsupported_numbers(whole, verify.allowed_numbers([ZOOM_RAW]))))
        self.assertEqual(verify.unsupported_numbers(whole, verify.allowed_numbers([ZOOM_RAW], meta=meta)), [])
        res = self.verify(self.reply(meta), meta)
        self.assertTrue(res.ok, res.error)

    def test_every_spelling_of_the_session_facts_is_accepted(self):
        for label, (start, duration, header, spellings) in FACT_CASES.items():
            meta = self.meta(start, duration)
            self.assertEqual(meta["time"], header, label)
            allowed = verify.allowed_numbers([ZOOM_RAW], meta=meta)
            for spelling in spellings:
                with self.subTest(case=label, spelling=spelling):
                    self.assertEqual(verify.unsupported_numbers(f"- Recording: {spelling}.", allowed), [])
                    res = self.verify(self.reply(meta, f" ({spelling})"), meta)
                    self.assertTrue(res.ok, res.error)

    def test_numbers_that_are_not_session_facts_are_still_rejected(self):
        invented = " The call mentions USD 4,200, a 38 percent discount, 6 sites and a launch in 2027."
        for label, (start, duration, _header, spellings) in FACT_CASES.items():
            meta = self.meta(start, duration)
            with self.subTest(case=label):
                bad = verify.unsupported_numbers(f"- {spellings[-1]}.{invented}", verify.allowed_numbers([ZOOM_RAW], meta=meta))
                self.assertEqual(bad, ["2027", "38", "4200", "6"])
                res = self.verify(self.reply(meta, " " + spellings[-1] + "." + invented), meta)
                self.assertEqual((res.ok, res.error_kind), (False, "rejected"))
                self.assertIn("numbers not found in the transcript: 2027, 38, 4200, 6", res.error)

    def test_a_number_of_the_transcript_text_still_counts_and_the_asr_header_still_does_not(self):
        meta = self.meta("2026-10-10T17:17:09+09:00", 321.0)
        self.assertEqual(verify.unsupported_numbers("- transcribed with whisper large-v3", verify.allowed_numbers([ZOOM_RAW], meta=meta)),
                         ["3"])

    def test_a_rejection_names_the_number_and_the_log_names_the_line(self):
        meta = self.meta("2026-10-10T17:17:09+09:00", 321.0)
        with self.assertLogs("mcap.verify", "WARNING") as logs:
            res = self.verify(self.reply(meta, "\n- the user spoke 3 short sentences."), meta)
        self.assertEqual((res.ok, res.error), (False, "numbers not found in the transcript: 3"))
        self.assertTrue(any("the user spoke 3 short sentences" in line for line in logs.output), logs.output)

    def test_metadata_numbers_are_derived_from_the_facts_not_only_from_the_header_text(self):
        meta = self.meta("2026-10-10T23:50:30+09:00", 3900.0)
        atoms = verify.metadata_numbers(meta)
        self.assertTrue({"2026", "26", "10", "11", "23", "11", "50", "0", "55", "12", "1", "5", "65", "3900"} <= atoms, sorted(atoms))
        self.assertNotIn("38", atoms)
        other = verify.metadata_numbers({"title": "Q3 Review", "platform_label": "Zoom Workplace 6", "calendar": {"attendees": ["dev2@example.com"]}})
        self.assertEqual(other, {"3", "6", "2"})                                          # title, platform and attendees as written
        self.assertEqual(verify.metadata_numbers({}), set())
        self.assertEqual(verify.metadata_numbers({"date": "garbage", "time": "unknown", "duration_sec": "x"}), set())


# ---------------------------------------------------------------------------------- facts only in the shape of a fact (wave E review)
# The first version of the fix accepted every number of the session facts ANYWHERE in the body: for the 17:17 call that is 0, 5, 17, 21,
# 22, 26, 321, 2026 (and 10), so "price 17", "5 sites", "10% discount", "USD 22" or "26 participants" were "supported" by the header.
# A session fact now counts where the text states a time, a length of time or a date with it.
EVIDENCE = {"date": "2026-10-10", "time": "17:17-17:22 KST (5m)", "duration_sec": 321.0, "title": "Zoom", "platform_label": "Zoom",
            "calendar": None}
RAW_NO_NUMBERS = "# Transcript\n\n[00:00:41] Me\nThis is a sample sentence for the synthetic transcript, nothing more.\n"


class FactShapeTests(unittest.TestCase):
    def bad(self, text, meta=EVIDENCE, raw=RAW_NO_NUMBERS):
        return verify.unsupported_numbers(text, verify.allowed_numbers([raw], meta=meta))

    def test_the_same_digits_as_a_price_a_count_a_percent_or_another_date_are_rejected(self):
        invented = ["The price is 17 per seat.", "5 sites were discussed.", "10% discount.", "5 action items.", "Budget USD 22.",
                    "Deadline: 21 October.", "| Me | Send the 5 reports | 17 |", "**5** attendees", "26 participants", "321 users",
                    "$5m raised", "5 days", "10 days", "17 sites", "Next sync 2026-10-17", "Next sync 10/17", "Next sync 26.10.17", "Next sync 2026.10.17", "5일 이내 완료", "3분기 매출", "version 5.22",
                    "22 patients", "17.5%", "17명", "22건", "0 decisions", "the 5th item", "Q5", "5 minutes' worth of 10 slides",
                    "a 10 minute demo", "meeting on 2026-22-17"]
        for text in invented:
            with self.subTest(text):
                self.assertNotEqual(self.bad(f"- {text}"), [], text)

    def test_the_facts_in_the_shape_of_a_time_a_length_or_a_date_are_accepted(self):
        stated = ["Time: 17:17-17:22 KST (5m)", "17:17 to 17:22 KST", "5 min 21 s in total", "321 seconds", "5분 21초", "5m 21s", "05:21 long",
                  "5:17 PM to 5:22 PM", "오후 5시 17분", "on 2026-10-10", "10/10/26", "2026년 10월 10일", "Oct 10", "Oct 10, 2026", "10 Oct 2026",
                  "October 10th", "2026.10.10", "2026.10.10.", "26.10.10", "a 5-minute call", "about 5 minutes", "~5 min", "5분간 진행", "5분짜리 통화", "5pm",
                  "17시 17분", "(UTC+9)", "5 mins", "Date: 2026-10-10", "5분 남짓", "10월 10일 17:17에 시작", "the call lasted 5m21s",
                  "2026-10-10 17:17 KST", "The recording (5 min 21 s)", "17:17\u201317:22", "10th of October", "5 min.", "5 min,", "5 minutes."]
        for text in stated:
            with self.subTest(text):
                self.assertEqual(self.bad(f"- {text}"), [], text)

    def test_a_time_fact_is_not_a_date_and_a_date_fact_is_not_a_length(self):
        """17 is an hour of this call (not a day), 10 is the month and the day (not a length of time), 5 is a length (not a day)."""
        for text in ("on 2026-10-17", "10/17/26", "Oct 17", "17 Oct", "10 minutes", "10분", "10 seconds", "5일", "5월", "June 5", "5 Oct"):
            with self.subTest(wrong=text):
                self.assertNotEqual(self.bad(f"- {text}"), [], text)
        for text in ("Oct 10", "10 Oct", "10일", "10월", "17:17", "5분", "5 minutes", "17시", "0 hours", "0시간"):
            with self.subTest(right=text):
                self.assertEqual(self.bad(f"- {text}"), [], text)

    def test_numbers_of_the_transcript_stay_supported_wherever_they_stand(self):
        raw = "# Transcript\n\n[00:00:41] Me\nWe have 17 sites and about 5 percent growth, call it 22 patients.\n"
        self.assertEqual(self.bad("- 17 sites, 5% growth, 22 patients, 17 per seat", raw=raw), [])
        self.assertEqual(self.bad("- 17 sites, 5% growth, 26 patients", raw=raw), ["26"])

    def test_title_platform_and_attendee_numbers_still_count_anywhere(self):
        meta = dict(EVIDENCE, title="Q3 Review of 2 sites", calendar={"attendees": ["Dev 7"]})
