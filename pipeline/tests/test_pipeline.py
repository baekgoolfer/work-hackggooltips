class ApiNothingLeaksTests(ApiPipelineBase):
    """Canary scan: the fake key must not appear in any file of the world, any log line, any printed text or any argv, also when the
    fake claude echoes it in its errors and its stderr."""

    def test_success_and_every_failure_leave_no_trace_of_the_key(self):
        stream = io.StringIO()
        handler = logging.StreamHandler(stream)
        handler.setFormatter(logging.Formatter("%(levelname)s %(name)s: %(message)s"))
        root_logger = logging.getLogger()
        root_logger.addHandler(handler)
        old_level = root_logger.level
        root_logger.setLevel(logging.DEBUG)
        self.addCleanup(root_logger.removeHandler, handler)
        self.addCleanup(root_logger.setLevel, old_level)
        apikey.install_log_redaction()
        results = []
        for n, scenario in enumerate((
                {"runs": [{"mode": "success", "note": sample_note()}]},
                {"runs": [{"mode": "crash"}, {"mode": "crash"}], "cleanup": {"mode": "crash"}, "leak_key": True},
                {"runs": [{"mode": "api_401"}], "cleanup": {"mode": "api_401"}, "leak_key": True},
                {"runs": [{"mode": "api_credit"}], "cleanup": {"mode": "api_credit"}, "leak_key": True},
                {"runs": [{"mode": "fallback_login", "note": sample_note()}], "cleanup": {"mode": "fallback_login"}, "leak_key": True})):
            sid = f"2026-10-07_{14 + n}00_meet"
            src = make_session(self.cfg, sid, start=f"2026-10-07T{14 + n}:00:12+09:00", end=f"2026-10-07T{14 + n}:50:00+09:00")
            self.fake.set(**scenario)
            results.append(pipeline.process_session(src, self.cfg, deps=self.asr.deps()))
        self.assertTrue(results[0].ok)
        self.assertEqual([r.error_kind for r in results[1:]], ["crashed", "auth", "credit_exhausted", "billing_mode_violation"])
        # the crash message carries the (masked) stderr of the child: proof that the leak really happened in the fake
        self.assertIn("boom: network unreachable", results[1].error)
        printed = "\n".join(str(v) for r in results for v in (r.error, r.warning))
        self.assertEqual(canary_hits(self.root, extra=(stream.getvalue(), printed)), [])
        self.assertIn("sk-ant-***", stream.getvalue() + printed + "".join(
            p.read_text(encoding="utf-8", errors="replace") for p in self.root.rglob("state.json")))

    def test_the_session_folder_the_archive_and_the_usage_log_never_hold_the_key(self):
        result = self.run_api(cost=0.4, leak_key=True)
        self.assertTrue(result.ok, result.error)
        self.assertEqual(canary_hits(self.root), [])
        self.assertNotIn("CANARY", usage.usage_path(self.cfg).read_text(encoding="utf-8"))


