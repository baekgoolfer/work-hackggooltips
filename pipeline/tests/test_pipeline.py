        final = self.published().final_dir
        before = (final / "meeting-note.md").read_text(encoding="utf-8")
        failing = StubNote(ok=False, kind="overloaded", error="Claude API overloaded or unavailable (HTTP 529)")
        res = self.run_pipeline(final, stub=failing, from_stage="note")
        self.assertFalse(res.ok)
        self.assertEqual((final / "meeting-note.md").read_text(encoding="utf-8"), before)      # old note untouched
        st = json.loads((final / "state.json").read_text())
        self.assertEqual(st["stage"], "failed")
        self.assertTrue(st["done"]["note"])
        better = StubNote(text=sample_note(extra="REGENERATED"))
        res = self.run_pipeline(final, stub=better, from_stage="note")
        self.assertTrue(res.ok)
        self.assertIn("REGENERATED", (final / "meeting-note.md").read_text(encoding="utf-8"))
        self.assertEqual(self.asr.asr_calls, 1)
        self.assertFalse((final / "state.json").exists())

