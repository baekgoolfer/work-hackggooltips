class Base(TempCase):
    def setUp(self):
        super().setUp()
        self.fake = FakeClaude(self.root / "fake")
        self.cfg = make_cfg(self.root, self.fake, note_timeout_seconds=60)
        self.asr = FakeASR()
        self.src = make_session(self.cfg)
        self.stub = StubNote()

    def deps(self, stub=None, **extra):
        stub = self.stub if stub is None else stub
        kwargs = {"check_ready": ready_ok, "generate_note": stub}
        kwargs.update(extra)
        return self.asr.deps(**kwargs)

    def run_pipeline(self, target=None, stub=None, deps_extra=None, **kw):
        return pipeline.process_session(target or self.src, self.cfg, deps=self.deps(stub, **(deps_extra or {})), **kw)

    def archive_folders(self):
        root = self.cfg.archive_dir
        return sorted(p for m in root.iterdir() if m.is_dir() for p in m.iterdir() if p.is_dir()) if root.exists() else []

    def tombstone(self):
        return json.loads((self.src / "state.json").read_text(encoding="utf-8"))


